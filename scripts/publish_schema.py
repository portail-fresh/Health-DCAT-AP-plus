#!/usr/bin/env python
"""Write the schema files served at the w3id permalink (docs/schema/*.yaml).

  https://w3id.org/portail-fresh/Health-DCAT-AP-plus/latest/schema/<file>

That address is what other schemas put in their `imports:` (ResHealth-DCAT-AP
does), so what is published there has to be something LinkML can import. The
LinkML project template's default -- `gen-yaml <source> > docs/schema/<name>.yaml`
-- is not:

  gen-yaml's output is the *merged* schema. It copies every element of every
  imported schema into itself (here: all 51 dcat-ap-plus classes, next to our
  own 21) and yet still lists the same `imports:`. A schema importing it
  therefore sees each dcat-ap-plus class twice -- once copied into the merged
  file, once re-imported through the file's own `dcatap_plus:` import -- and
  LinkML's legacy SchemaLoader (what gen-yaml, PythonGenerator, gen-project
  and linkml-run-examples use; SchemaView does not care) refuses with
  `Conflicting URIs (...) for item: Activity`. Until 2026-10-19 this was
  blamed on "two levels of stacked CURIE imports"; the duplicated definitions
  were the actual cause (reproduced and confirmed by publishing the source
  file instead -- see docs/architecture-verification.md).

So three files are written here:

  health_dcat_ap_plus.yaml          the SOURCE root schema, unchanged except
                                    for one thing: bare sibling imports
                                    become absolute URLs (below).
  healthdcat_ap_non_public.yaml     the sibling it imports, verbatim.
  health_dcat_ap_plus.merged.yaml   gen-yaml's merged output, for anyone who
                                    wants the whole model in one file. NOT
                                    importable -- its banner says so.

Why the sibling import is rewritten: the source imports its sibling as a bare
name (`healthdcat_ap_non_public`), which is right for local work -- it
resolves next to the file, never from the network. But when a downstream
schema pulls the *published* root in, the legacy loader resolves that bare
name against the DOWNSTREAM schema's own directory (it hands nested imports
to the root's base_dir, not to the file that declared them) and fails with
FileNotFoundError. The `./name` form exists for exactly this (LinkML 1.12.1's
resolve_merged_imports rewrites it relative to the importing file) but builds
the result with pathlib/os.path, so on Windows it comes out as
`...latest\\schema\\name` and 404s. An absolute URL needs neither and works on
every platform and in every loader -- confirmed by serving each variant from
a local stand-in for w3id and generating Python, YAML, Pydantic, SHACL, OWL,
JSON Schema and the JSON-LD context from ResHealth-DCAT-AP with no importmap
at all. Only the published copy is rewritten; the source keeps the bare name.

Regenerate with `just gen-doc` (it runs this) or
`uv run python scripts/publish_schema.py`.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
SCHEMA_NAME = "health_dcat_ap_plus"
SOURCE_DIR = REPO_ROOT / "src" / SCHEMA_NAME / "schema"
DEST_DIR = REPO_ROOT / "docs" / "schema"

# docs/schema/<file> is served as <schema id>/latest/schema/<file> -- the
# w3id rule (perma-id/w3id.org#6598) maps latest/schema/ onto GitHub Pages'
# schema/ folder. A versioned path would go here if docs ever get versioned.
PERMALINK_SUBPATH = "latest/schema"

PUBLISHED_BANNER = """\
# PUBLISHED COPY -- generated by scripts/publish_schema.py (run by `just
# gen-doc`); do not edit. Identical to
# src/health_dcat_ap_plus/schema/health_dcat_ap_plus.yaml except that sibling
# imports are absolute URLs, so a schema importing this file needs no
# importmap. Import THIS file, not health_dcat_ap_plus.merged.yaml.
"""

MERGED_BANNER = """\
# MERGED SNAPSHOT -- generated by scripts/publish_schema.py (gen-yaml's
# output); do not edit. Every element of every imported schema is copied into
# this file, yet the `imports:` list below is still there: importing THIS file
# from another schema defines each of those elements twice, and LinkML's
# legacy loader fails with "Conflicting URIs". Read it if you want the whole
# model in one place; to import the schema, use health_dcat_ap_plus.yaml.
"""


def _is_bare_sibling(imp: str) -> bool:
    """A bare name: not a CURIE (`linkml:types`), not a URL, not an explicit path."""
    return ":" not in imp and "/" not in imp and "\\" not in imp and not imp.startswith(".")


def _rewrite_imports_block(text: str, replacements: dict[str, str]) -> str:
    """Replace `- name` entries of the top-level `imports:` block, line by line.

    Text-level on purpose: the source file is full of comments worth keeping
    in the published copy, which a YAML round trip would drop. The result is
    re-parsed and compared with the source by publish() before it is written.
    """
    lines = text.split("\n")
    try:
        start = next(i for i, line in enumerate(lines) if line.rstrip() == "imports:") + 1
    except StopIteration:
        raise SystemExit("no top-level `imports:` block found in the source schema") from None
    remaining = dict(replacements)
    for i in range(start, len(lines)):
        line = lines[i]
        if line and not line[0].isspace() and not line.startswith(("-", "#")):
            break  # next top-level key
        stripped = line.strip()
        if not stripped.startswith("- "):
            continue
        item = stripped[2:].split("#", 1)[0].strip().strip("'\"")
        if item in remaining:
            lead = line[: len(line) - len(line.lstrip())]
            lines[i] = f"{lead}- {remaining.pop(item)}"
    if remaining:
        raise SystemExit(
            f"import(s) {sorted(remaining)} not found as block-style `- name` lines in the `imports:` "
            "block -- publish_schema.py only rewrites that form; extend it before using flow style"
        )
    return "\n".join(lines)


def render_published(source_dir: Path = SOURCE_DIR) -> dict[str, str]:
    """File name -> text of every file that must sit next to the published root."""
    root_text = (source_dir / f"{SCHEMA_NAME}.yaml").read_text(encoding="utf-8")
    source = yaml.safe_load(root_text)
    base = f"{source['id'].rstrip('/')}/{PERMALINK_SUBPATH}"

    files: dict[str, str] = {}
    replacements: dict[str, str] = {}
    for imp in source.get("imports") or []:
        if not _is_bare_sibling(imp):
            continue
        sibling = source_dir / f"{imp}.yaml"
        if not sibling.is_file():
            raise SystemExit(f"{SCHEMA_NAME}.yaml imports {imp!r}, but {sibling} does not exist")
        replacements[imp] = f"{base}/{imp}"
        files[f"{imp}.yaml"] = sibling.read_text(encoding="utf-8")

    published_text = PUBLISHED_BANNER + _rewrite_imports_block(root_text, replacements)

    # Verify rather than trust the text rewrite: the published file must be
    # the source with nothing but those import entries changed.
    published = yaml.safe_load(published_text)
    expected = dict(source)
    expected["imports"] = [replacements.get(imp, imp) for imp in source.get("imports") or []]
    if published != expected:
        raise SystemExit("published root differs from the source in more than its sibling imports")

    files[f"{SCHEMA_NAME}.yaml"] = published_text
    return files


def publish(dest_dir: Path = DEST_DIR, source_dir: Path = SOURCE_DIR) -> list[Path]:
    dest_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in render_published(source_dir).items():
        path = dest_dir / name
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written


def write_merged(dest_dir: Path = DEST_DIR, source_dir: Path = SOURCE_DIR) -> Path:
    from linkml.generators.yamlgen import YAMLGenerator  # slow import; the rest of the script doesn't need it

    merged = YAMLGenerator(str(source_dir / f"{SCHEMA_NAME}.yaml")).serialize()
    path = dest_dir / f"{SCHEMA_NAME}.merged.yaml"
    path.write_text(MERGED_BANNER + merged, encoding="utf-8", newline="\n")
    return path


def main() -> None:
    for path in [*publish(), write_merged()]:
        print(f"Wrote {path.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
